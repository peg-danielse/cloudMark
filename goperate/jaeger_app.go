package main

// Social-network side of the Jaeger integration (shared machinery in
// jaegercp.go).
//
// Sampling: the C++ services call SetUpTracer("config/jaeger-config.yml"),
// relative to their working directory, and jaeger-client-cpp does not read
// env. The repo's config/jaeger-config.yml has sampler const 0, so tracing
// is off by default. With -jaeger, goperate writes a per-run directory
// (<traces dir>/social-cwd/config/) holding a generated jaeger-config.yml
// (sampler probabilistic -trace-sample; reporter endpoint
// http://-jaeger-host:14268+offset/api/traces, or localAgentHostPort
// :6831+offset with -trace-transport udp) and a symlink to the real
// service-config.json, and passes SOCIAL_RUNDIR=<dir> to the run/ wrappers,
// which cd there instead of the repo root. The repo's config is never edited
// and the services are not rebuilt; without -jaeger nothing changes.

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"
)

const envSocialRunDir = "SOCIAL_RUNDIR"

// socialMemcached: which memcached (program basename = port) each service's
// mmc/memcached spans talk to (service-config.json *-memcached).
var socialMemcached = map[string]string{
	"user-service":         "11311",
	"user-mention-service": "11311",
	"post-storage-service": "11312",
	"url-shorten-service":  "11313",
}

// socialServiceDaemon maps a tracer service name to its run/ binary:
// compose-post-service -> ComposePostService (inverse of serviceKey).
func socialServiceDaemon(svc string) string {
	var b strings.Builder
	for _, part := range strings.Split(svc, "-") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// socialTraceModel: the route is the one whose entry service owns the root
// span (the loadgen's Thrift calls carry an empty carrier, so the entry
// service starts the trace); store calls are charged by span name.
func socialTraceModel() traceModel {
	rootRoute := map[string]string{}
	for route, svc := range routeService {
		rootRoute[svc] = route
	}
	return traceModel{
		route:   func(root *traceSpan) string { return rootRoute[root.service] },
		service: socialServiceDaemon,
		backend: func(s *traceSpan) string {
			n := strings.ToLower(s.name)
			switch {
			case s.service == "compose-post-service" && n == "write_home_timeline_client":
				return "rabbitmq-server" // publish; the consumer runs after the request returns
			case strings.Contains(n, "rabbitmq") || strings.Contains(n, "amqp"):
				return "rabbitmq-server"
			case strings.Contains(n, "redis"):
				return "redis-server"
			case strings.Contains(n, "mongo"):
				return "mongod"
			case strings.Contains(n, "mmc") || strings.Contains(n, "memcached"):
				if d, ok := socialMemcached[s.service]; ok {
					return d
				}
				return "memcached"
			}
			return ""
		},
	}
}

// socialJaegerYAML is the jaeger-client-cpp config for this run.
func socialJaegerYAML(o *jaegerOpts) string {
	reporter := "  endpoint: " + o.collectorHTTP()
	if o.transport == "udp" {
		reporter = "  localAgentHostPort: " + o.agentUDP()
	}
	return fmt.Sprintf(`# generated by goperate -jaeger (%s); see goperate/jaeger_app.go
disabled: false
reporter:
  logSpans: false
  queueSize: 10000
  bufferFlushInterval: 1
%s
sampler:
  type: probabilistic
  param: %s
`, time.Now().Format(time.RFC3339), reporter, o.sampleString())
}

// socialCwd is -run-dir (or the default goperate picks for a moved -config); empty: next to traces.csv.
var socialCwd string

func socialRunDir() string {
	if socialCwd != "" {
		return socialCwd
	}
	return filepath.Join(filepath.Dir(tracing.out), "social-cwd")
}

// prepareSocialRunDir writes <dir>/config/jaeger-config.yml and links
// <dir>/config/service-config.json to serviceConfig.
func prepareSocialRunDir(dir, serviceConfig string) error {
	cfgDir := filepath.Join(dir, "config")
	if err := os.MkdirAll(cfgDir, 0o755); err != nil {
		return err
	}
	yaml := []byte(socialJaegerYAML(tracing))
	if !tracing.enabled() {
		var err error
		if yaml, err = os.ReadFile(filepath.Join(snRoot, "config", "jaeger-config.yml")); err != nil {
			return err
		}
	}
	if err := os.WriteFile(filepath.Join(cfgDir, "jaeger-config.yml"), yaml, 0o644); err != nil {
		return err
	}
	abs, err := filepath.Abs(serviceConfig)
	if err != nil {
		return err
	}
	link := filepath.Join(cfgDir, "service-config.json")
	_ = os.Remove(link)
	return os.Symlink(abs, link)
}

// addTraceEnv points the C++ service wrappers at the per-run config directory.
func addTraceEnv(line tuple, env map[string]string) map[string]string {
	if !(tracing.enabled() || socialCwd != "") || !strings.HasSuffix(filepath.Base(line.path), "Service") {
		return env
	}
	if env == nil {
		env = map[string]string{}
	}
	env[envSocialRunDir] = socialRunDir()
	return env
}

func socialOutputDir() string { return filepath.Join(snRoot, "output") }

func defaultGenOut() string {
	return filepath.Join(socialOutputDir(), fmt.Sprintf("loadgen-%d.out", time.Now().Unix()))
}

func jaegerLogPath() string {
	return strings.TrimSuffix(tracing.out, filepath.Ext(tracing.out)) + ".jaeger.log"
}

// beginTraceAnalysis returns the writer autoscale prints route lines to and a
// finish function (see hotel operate/jaeger_app.go).
func beginTraceAnalysis() (io.Writer, func(), error) {
	if !tracing.enabled() {
		return appOut, func() {}, nil
	}
	out := lockedWriter{mu: &sync.Mutex{}, w: appOut}
	var cpOut io.Writer
	if tracing.cpLines {
		cpOut = out
	}
	t, err := newCPTracer(tracing.queryBase(), socialTraceModel(), tracing.out, cpOut, tracing.lag, tracing.depth)
	if err != nil {
		return nil, nil, err
	}
	fmt.Printf("traces csv %s query %s sample %s lag %s depth %d\n", tracing.out, tracing.queryBase(), tracing.sampleString(), tracing.lag, tracing.depth)
	return &lineSniffer{w: out, on: t.onLine}, func() { fmt.Println(t.close()) }, nil
}
